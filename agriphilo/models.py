"""Data contracts between pipeline stages.

DatasetSpec (Customer Agent) -> OrchestratorPlan (Orchestrator Agent) -> EnvironmentPlan (Environment Agent)
-> SimJob (expanded in code) -> human play (game server) + AI players (simulator) -> SimResult
-> Manifest (Data Collection) -> QAMetrics (code) + QAReport (QA Agent) -> Quote (Payment Agent) -> Payment.
"""
from typing import Dict, List, Literal, Optional

from pydantic import BaseModel, Field, model_validator

from .dataset_spec import CameraSpec, DatasetSpec, Sensor, SuccessRule


# ---- Orchestrator Agent ----------------------------------------------------------------------

class PlanStep(BaseModel):
    stage: Literal["environment", "play", "simulation", "collection", "qa", "quote"]
    agent: str = Field(description="Who does it, e.g. 'Environment Agent', 'Human player', 'AI players'")
    action: str = Field(description="What they do, concretely, in MuJoCo/RoboCasa terms")
    output: str = Field(description="What this step hands to the next one")


class TaskStage(BaseModel):
    name: str
    success_check: str = Field(description="How the simulator decides this stage is done")


class DataSourcing(BaseModel):
    human_demos: int = Field(ge=0, le=50, description="Episodes a human plays in the browser game")
    ai_episodes: int = Field(ge=1, le=10000, description="Episodes generated by AI players")
    method: str = Field(description="How AI players produce episodes, e.g. demo augmentation + scripted policy")


class OrchestratorPlan(BaseModel):
    simulator: Literal["mujoco"] = "mujoco"
    framework: Literal["robocasa"] = "robocasa"
    steps: List[PlanStep] = Field(min_length=4)
    scene_build: List[str] = Field(min_length=1, description="How the scene is assembled, in order")
    task_stages: List[TaskStage] = Field(min_length=1)
    data_sourcing: DataSourcing
    data_mapping: List[str] = Field(min_length=1, description="Which recorded stream fills each requested field")
    qa_criteria: List[str] = Field(min_length=1)
    risks: List[str] = Field(default_factory=list)
    rationale: str


# ---- Environment Agent -----------------------------------------------------------------------

MAX_LAYOUT_ID = 60
MAX_STYLE_ID = 60


class EnvironmentPlan(BaseModel):
    simulator: Literal["mujoco"] = "mujoco"
    scene_template: Literal["robocasa_cafe_counter"] = "robocasa_cafe_counter"
    task: Literal["CafeServeCoffee"] = "CafeServeCoffee"
    robot: Literal["PandaOmron"] = "PandaOmron"
    layout_ids: List[int] = Field(min_length=1, description=f"Counter layouts 1..{MAX_LAYOUT_ID} to sample from")
    style_ids: List[int] = Field(min_length=1, description=f"Visual styles 1..{MAX_STYLE_ID} to sample from")
    cameras: List[CameraSpec] = Field(min_length=1)
    control_hz: int = Field(ge=10, le=30)
    max_steps: int = Field(ge=50, le=20000)
    object_instance_randomization: bool = Field(description="Sample different mug/tray models per episode")
    placement_jitter_m: float = Field(ge=0, le=0.05, description="Random xy jitter of object placements")
    base_seed: int = Field(ge=0, lt=2**31)
    focus: List[str] = Field(default_factory=list, description="What the scene should stress, in plain words")
    rationale: str

    @model_validator(mode="after")
    def _valid(self):
        for name, ids, hi in (("layout_ids", self.layout_ids, MAX_LAYOUT_ID), ("style_ids", self.style_ids, MAX_STYLE_ID)):
            bad = [i for i in ids if not 1 <= i <= hi]
            if bad:
                raise ValueError(f"{name} out of range 1..{hi}: {bad}")
            if len(set(ids)) != len(ids):
                raise ValueError(f"{name} has duplicates")
        return self


# ---- Simulation job (expanded deterministically from the plan) ----------------------------

class EpisodeParams(BaseModel):
    episode_id: str
    seed: int
    layout_id: int
    style_id: int
    placement_jitter_m: float
    player: Literal["ai", "human"] = "ai"


class SimJob(BaseModel):
    job_id: str
    order_id: str
    spec: DatasetSpec
    plan: EnvironmentPlan
    episodes: List[EpisodeParams]
    sensors: List[Sensor]
    success_rule: SuccessRule
    output_format: Literal["hdf5"] = "hdf5"


class EpisodeSummary(BaseModel):
    episode_id: str
    seed: int
    success: bool
    failure_reason: Optional[str] = None
    steps: int
    stages_completed: int


class SimResult(BaseModel):
    job_id: str
    worker: str = Field(description="Which simulator produced the data, e.g. 'mock-ai-players'")
    simulator_version: str
    dataset_path: str
    episodes: List[EpisodeSummary]
    compute_seconds: float


