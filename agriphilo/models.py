# ---- QA -------------------------------------------------------------------------------------

class QACheck(BaseModel):
    name: str
    category: Literal["structure", "task", "diversity", "reproducibility"]
    status: Literal["pass", "warn", "fail"]
    detail: str


class EpisodeQA(BaseModel):
    episode_id: str
    valid: bool
    success: bool
    reasons: List[str] = Field(default_factory=list)


class CoverageBin(BaseModel):
    lo: float
    hi: float
    count: int
    success_rate: Optional[float]


class QAMetrics(BaseModel):
    episodes_total: int
    episodes_valid: int
    success_rate: float
    failure_reasons: Dict[str, int]
    coverage: Dict[str, List[CoverageBin]]
    duplicate_seeds: int
    repro_checked: int
    repro_matched: int
    checks: List[QACheck]
    episodes: List[EpisodeQA]


class QAReport(BaseModel):
    verdict: Literal["pass", "pass_with_notes", "fail"]
    headline: str
    findings: List[str] = Field(min_length=1)
    recommended_fixes: List[str] = Field(default_factory=list)
    rerun_needed: bool = False
    rerun_focus: Optional[str] = Field(None, description="What the Environment Agent should change on a rerun")


# ---- Payment --------------------------------------------------------------------------------

class LineItem(BaseModel):
    sku: str
    description: str
    quantity: float = Field(gt=0)
    unit: str
    unit_price_usd: float
    amount_usd: float


class Quote(BaseModel):
    line_items: List[LineItem] = Field(min_length=1)
    subtotal_usd: float
    total_usd: float
    currency: Literal["USD"] = "USD"
    valid_days: int = Field(ge=1, le=90)
    notes: List[str] = Field(default_factory=list)


class Payment(BaseModel):
    status: Literal["paid"]
    mode: Literal["test", "stripe_test"] = "test"
    amount_usd: float
    reference: str
    paid_at: float
